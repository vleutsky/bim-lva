-- Лицензия может существовать без аккаунта в кабинете.
-- Выполните в SQL Editor ПОСЛЕ 20260806140000_licenses_lic_format.sql.
--
-- Зачем: часть лицензий выдана офлайн-скриптом Tools\New-LvaLicense.ps1 — они
-- уже работают у клиентов, но в базе сайта их нет, и список «Выданные лицензии»
-- в кабинете пуст, хотя фактически ключи выданы. Учесть их мешало требование
-- user_id NOT NULL: у получателя может не быть регистрации в кабинете вообще
-- (лицензия node-locked, она привязана к железу, а не к аккаунту), а заводить
-- пользователю аккаунт только чтобы строка появилась в списке — лишнее.
--
-- Выдача через сайт при этом не меняется: там user_id по-прежнему берётся из
-- заявки и остаётся заполненным. Пусто он бывает только у импортированных.

alter table public.licenses
  alter column user_id drop not null;

comment on column public.licenses.user_id is
  'Аккаунт получателя. Пусто — лицензия учтена без регистрации в кабинете (обычно выдана офлайн-скриптом).';

-- Политика чтения осталась той же по смыслу, но переписана явно: строку без
-- user_id не должно быть видно никому, кроме админов. При сравнении null = uuid
-- Postgres даёт null (не true), поэтому обычный пользователь такие строки и не
-- видел; пересоздаём политику, чтобы это было записано в коде, а не следовало
-- из тонкостей трёхзначной логики.
drop policy if exists licenses_select_own on public.licenses;
create policy licenses_select_own on public.licenses
  for select using (
    (user_id is not null and user_id = auth.uid())
    or public.is_license_admin()
  );
