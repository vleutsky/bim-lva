-- Позволяет учитывать лицензии, выданные офлайн (Tools\New-LvaLicense.ps1),
-- без требования, чтобы получатель был зарегистрирован в кабинете BIM.LVA.
--
-- Раньше public.licenses.user_id был NOT NULL — строку нельзя было вставить
-- без реального аккаунта auth.users. Для веб-выдачи (через заявку в кабинете)
-- это верно и остаётся так. Но офлайн-лицензии выдаются людям, у которых
-- кабинета может не быть вовсе — им нужен только файл license.lic, а не
-- личный кабинет. Импорт такой лицензии «для учёта» не должен требовать
-- регистрации ради самого факта регистрации.

alter table public.licenses
  alter column user_id drop not null;

-- RLS не меняется: licenses_select_own уже пускает админа по
-- is_license_admin() независимо от user_id, а обычному пользователю
-- (user_id = auth.uid()) строка с NULL user_id просто никогда не попадётся —
-- сравнение с NULL в SQL всегда ложно, ничего дополнительно закрывать не надо.

comment on column public.licenses.user_id is
  'Аккаунт получателя в кабинете BIM.LVA. NULL — лицензия выдана офлайн '
  'человеку без аккаунта; видна только админу, в "Мои заявки" не попадает.';
